from telegram import Update
from telegram.ext import CallbackContext

from core.bot.keyboards.main_menu import (
    get_main_menu_keyboard,
    get_today_menu_keyboard,
)


def start(update: Update, context: CallbackContext):
    user = update.effective_user

    update.message.reply_text(
        (
            f"Привет, {user.first_name or 'друг'} 👋\n\n"
            "Это дневник благодарности и фокуса.\n"
            "2–5 минут в день — чтобы лучше чувствовать себя и свою жизнь.\n\n"
            "Начнём?\n"
            "Вот как всё устроено 👇\n"

            "🟡 Сегодня\n"  
            "— центр дня. Здесь ты можешь:\n"
            "• заполнить утро или вечер\n"
            "• посмотреть сегодняшние ответы\n"
            "• пропустить день, если не в ресурсе\n\n"

            "☀️ Утро\n"
            "— короткая настройка на день: фокус, намерение, поддержка себя.\n\n"

            "🌙 Вечер\n"
            "— подведение итогов: благодарность, лучшее за день, ощущение завершённости.\n\n"

            "📅 Неделя\n"
            "— задание и рефлексия недели.\n"
            "Помогает заметить общий вектор, а не только отдельные дни.\n\n"

            "📖 История\n"
            "— твои прошлые записи: по датам, по поиску и прогрессу.\n\n"

            "📊 Статистика\n"
            "— мягкий обзор без оценок:\n"
            "как часто ты заполняешь дневник и какие темы появляются чаще.\n\n"

            "⚙️ Настройки\n"
            "— напоминания, время, часовой пояс — всё под тебя.\n\n"

            "Можно начинать с любой кнопки.\n"
            "Если сегодня не хочется писать — это тоже нормально 💛\n\n"

            "Когда будешь готов — просто нажми «Сегодня»."
            "Нажми /start или /help в любой момент, чтобы вернуться сюда.\n\n"
        ),
        reply_markup=get_main_menu_keyboard(),
    )


